package build

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

const linkPath = "internal/datlylink/link_gen.go"
const statePath = "internal/datlylink/link_gen.sha256"
const linkStub = `// Code generated by datly project build. DO NOT EDIT.
package datlylink
import("github.com/viant/x";"github.com/viant/x/module")
func Registry()(*x.Registry,error){return x.NewRegistry(),nil}
func Workspace()*module.Workspace{return nil}
`

type managedFiles struct{ root string }

func (m managedFiles) hash(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}
func (m managedFiles) hashFile(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	return m.hash(data), nil
}
func (m managedFiles) read() ([]byte, error) {
	data, err := os.ReadFile(filepath.Join(m.root, linkPath))
	if err != nil {
		return nil, err
	}
	state, err := os.ReadFile(filepath.Join(m.root, statePath))
	if err != nil {
		return nil, err
	}
	if string(state) != m.hash(data) {
		return nil, fmt.Errorf("generated linker was edited: %s; preserve your changes before rebuilding", linkPath)
	}
	return data, nil
}
func (m managedFiles) write(data []byte) error {
	return m.replace(linkPath, data)
}
func (m managedFiles) commit(data []byte) error {
	return m.replace(statePath, []byte(m.hash(data)))
}
func (m managedFiles) restore(data []byte) error {
	if err := m.write(data); err != nil {
		return err
	}
	return m.commit(data)
}
func (m managedFiles) overlay() (string, func(), error) {
	dir, err := os.MkdirTemp("", "datly-link-overlay-*")
	if err != nil {
		return "", nil, err
	}
	cleanup := func() { _ = os.RemoveAll(dir) }
	stub := filepath.Join(dir, "stub.go")
	if err = os.WriteFile(stub, []byte(linkStub), 0600); err != nil {
		cleanup()
		return "", nil, err
	}
	data, err := json.Marshal(map[string]any{"Replace": map[string]string{filepath.Join(m.root, linkPath): stub}})
	if err != nil {
		cleanup()
		return "", nil, err
	}
	name := filepath.Join(dir, "overlay.json")
	if err = os.WriteFile(name, data, 0600); err != nil {
		cleanup()
		return "", nil, err
	}
	return name, cleanup, nil
}

func (m managedFiles) replace(path string, data []byte) error {
	target := filepath.Join(m.root, path)
	f, err := os.CreateTemp(filepath.Dir(target), ".datly-stage-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err = f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err = f.Chmod(0644); err != nil {
		f.Close()
		return err
	}
	if err = f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), target)
}
func (m managedFiles) lock() (func(), error) {
	path := filepath.Join(m.root, "internal/datlylink/.build-lock")
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return nil, fmt.Errorf("project build lock (another build or interrupted build): %w", err)
	}
	if err = f.Close(); err != nil {
		os.Remove(path)
		return nil, err
	}
	return func() { _ = os.Remove(path) }, nil
}
