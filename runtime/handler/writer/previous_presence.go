package writer

import (
	"fmt"
	"reflect"

	xhandler "github.com/viant/xdatly/handler"
)

// previousPresence delegates value comparison to the generated entity method.
// The writer only selects safe scalar markers; it does not compare values.
type previousPresence struct {
	method reflect.Value
	marker reflect.StructField
	fields []Field
}

func compilePreviousPresence(record *Record) error {
	entityPtr := reflect.PointerTo(record.EntityType)
	method, ok := entityPtr.MethodByName("SynchronizePresentMarker")
	if !ok {
		return nil // Existing external shapes must be regenerated by their owner.
	}
	if method.Type.IsVariadic() || method.Type.NumIn() != 2 || method.Type.In(0) != entityPtr || method.Type.In(1) != entityPtr || method.Type.NumOut() != 0 {
		return fmt.Errorf("%s.SynchronizePresentMarker must have signature func(*%s)", entityPtr, record.EntityType.Name())
	}
	marker, ok := record.EntityType.FieldByName("Has")
	if !ok || len(marker.Index) != 1 || marker.PkgPath != "" || marker.Type.Kind() != reflect.Pointer || marker.Type.Elem().Kind() != reflect.Struct || marker.Tag.Get("setMarker") != "true" {
		return fmt.Errorf("%s.SynchronizePresentMarker requires an owned pointer Has with setMarker metadata", entityPtr)
	}
	exclude := map[string]bool{}
	for _, key := range record.Keys {
		exclude[key.Name] = true
	}
	if field := record.ConcurrencyToken; field != nil {
		exclude[field.Name] = true
	}
	if field := record.DeleteMarker; field != nil {
		exclude[field.Name] = true
	}
	for _, relation := range record.Relations {
		exclude[record.EntityType.FieldByIndex(relation.Field).Name] = true
	}
	compiled := &previousPresence{method: method.Func, marker: marker}
	for _, field := range record.Fields {
		// Explicit audit values accompany a business update even when equal to
		// Previous. Omitting them may activate database ON UPDATE defaults.
		// restoreNoopAudit removes them when no business change remains.
		if !field.transient && !field.Audit && !exclude[field.Name] && len(field.Has) != 0 {
			compiled.fields = append(compiled.fields, field)
		}
	}
	record.previousPresence = compiled
	return nil
}

// synchronizePreviousPresence keeps original, identity, relation and control
// markers intact. Legacy generated methods may recurse, so they receive a
// separate marker with only loaded, supplied scalar fields enabled. Every child
// is compared independently against its own matched Previous frame.
func (p *Program) synchronizePreviousPresence(frame *Frame) {
	if frame == nil || frame.Record == nil || frame.Record.previousPresence == nil || frame.Action != xhandler.WriteUpdate ||
		frame.Record.Auxiliary || frame.Record.WriterActionPolicy == updateActionPolicy || !frame.Previous.IsValid() || !frame.Entity.IsValid() || frame.Entity.IsNil() {
		return
	}
	compiled := frame.Record.previousPresence
	loaded := p.previousFields[frame.Record]
	var selected []Field
	for _, field := range compiled.fields {
		if loaded.Has(field.Name) && supplied(frame.Entity.Elem(), field) {
			selected = append(selected, field)
		}
	}
	if len(selected) == 0 {
		return
	}
	copy := reflect.New(frame.Record.EntityType)
	copy.Elem().Set(frame.Entity.Elem())
	copy.Elem().FieldByIndex(compiled.marker.Index).Set(reflect.New(compiled.marker.Type.Elem()))
	for _, field := range selected {
		setSupplied(copy.Elem(), field, true)
	}
	compiled.method.Call([]reflect.Value{copy, frame.Previous})
	// A caller may reuse a marker pointer across rows. Keep clearing one row's
	// scalar flags from withdrawing a different row's actual change.
	liveMarker := frame.Entity.Elem().FieldByIndex(compiled.marker.Index)
	detached := reflect.New(compiled.marker.Type.Elem())
	if !liveMarker.IsNil() {
		detached.Elem().Set(liveMarker.Elem())
	}
	liveMarker.Set(detached)
	for _, field := range selected {
		setSupplied(frame.Entity.Elem(), field, supplied(copy.Elem(), field))
	}
}
