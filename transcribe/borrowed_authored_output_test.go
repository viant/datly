func TestBorrowedOwnerRetainsAuthoredOutput(t *testing.T) {
	type useCase struct{ description, binding, typeExpr, generatedFile, expected string }
	for _, tc := range []useCase{
		{"authored output DTO", "output/warnings", "[]*self.Warning", "output.go", "[]*Warning"},
		{"trusted owner parameter", "param/Options", "*self.Warning", "input.go", "*Warning"},
	} {
		t.Run(tc.description, func(t *testing.T) {
			testBorrowedOwnerAuthoredDependency(t, tc.binding, tc.typeExpr, tc.generatedFile, tc.expected)
		})
	}
}

// Each scenario is a causal regeneration/drift protocol on one captured source.
func testBorrowedOwnerAuthoredDependency(t *testing.T, binding, typeExpr, generatedFile, expected string) {
	root, owner, child, _ := borrowedAuxiliaryOwnerFixture(t)
	const packagePath = "github.com/viant/datly/auxownerfixture/generated"
	warningSource := "package generated\ntype Warning struct { Code string; Detail *WarningDetail }\ntype Unrelated struct { Value bool }\n"
	detailSource := "package generated\ntype WarningDetail struct { Message string }\n"
	writeSourceFile(t, root, "generated/warning.go", warningSource)
	writeSourceFile(t, root, "generated/warning_detail.go", detailSource)
	writeSourceFile(t, root, "generated/stale_output.go", "// Code generated by Datly for Stale; DO NOT EDIT.\npackage generated\ntype StaleWarning struct { Message string }\n")
	owner.Text = strings.Replace(owner.Text, "SELECT r.*", "#define($_ = $Warnings<"+typeExpr+">("+binding+"))\nSELECT r.*", 1)
	require.NoError(t, os.WriteFile(owner.Path, []byte(owner.Text), 0600))
	var err error
	owner.Types, err = freshBorrowedForeignTypes(t.Context(), owner, owner.Text)
	require.NoError(t, err)
	var depsInitial *borrowedOutputDependencies
	_, depErr := freshBorrowedForeignTypes(t.Context(), owner, owner.Text, &depsInitial)
	require.NoError(t, depErr)
	require.True(t, depsInitial.names["Warning"], "%+v", depsInitial.names)
	for _, name := range []string{"Warning", "WarningDetail", "Unrelated", "Record", "RecordHas", "StaleWarning"} {
		_, found, err := owner.Types.Resolve(typecatalog.TranscribeAuthority, packagePath+"."+name)
		require.NoError(t, err)
		require.False(t, found, "output leaked into SQL discovery: %s", name)
	}
	// Normal owner generation already supports this authored output; load its
	// ordinary package authority rather than the deliberately restricted SQL set.
	require.NoError(t, owner.Types.RegisterPackage(typecatalog.TypeOriginPackage, owner.dependencySnapshot.Packages[packagePath]))
	_, err = (Generator{Operation: "patch"}).Generate(t.Context(), GenerationRequest{Source: owner, Destination: root})
	require.NoError(t, err)
	child.dependencySnapshot = nil // A new authoring invocation after adding the DTO.
	_, err = (Generator{Operation: "patch"}).Generate(t.Context(), GenerationRequest{Source: child, Destination: root})
	require.NoError(t, err)
	before := borrowedGeneratedSnapshot(t, root)
	for _, source := range []*Source{owner, child} {
		_, err = (Generator{Operation: "patch"}).Generate(t.Context(), GenerationRequest{Source: source, Destination: root})
		require.NoError(t, err)
	}
	require.Equal(t, before, borrowedGeneratedSnapshot(t, root))
	bytes, err := os.ReadFile(filepath.Join(root, "generated/warning.go"))
	require.NoError(t, err)
	require.Equal(t, warningSource, string(bytes))
	output, err := os.ReadFile(filepath.Join(root, "generated", generatedFile))
	require.NoError(t, err)
	require.Contains(t, string(output), expected)
	borrowedGeneratedModuleTest(t, root)
	compiled, err := NewCompiler().Compile(t.Context(), child)
	require.NoError(t, err)
	var proof *gen.BorrowedRowAuthority
	for _, view := range compiled.Views {
		if view != nil && view.Borrowed != nil {
			proof = view.Borrowed
		}
	}
	require.NotNil(t, proof)
	require.NoError(t, proof.ValidateFiles(func(path string) string { return path }))
	detailPath := filepath.Join(root, "generated/warning_detail.go")
	require.NoError(t, os.WriteFile(detailPath, []byte(strings.Replace(detailSource, "Message string", "Message int", 1)), 0600))
	require.Error(t, proof.ValidateFiles(func(path string) string { return path }), "transitive output DTO drift must invalidate captured proof")
	require.NoError(t, os.WriteFile(detailPath, []byte(detailSource), 0600))
	target := filepath.Join(root, "generated")
	require.NoError(t, os.Rename(target, target+".staged"))
	require.NoError(t, proof.ValidateSchema(), "staged validation must reuse captured output authority")
	require.NoError(t, os.Rename(target+".staged", target))
	// An output declaration cannot revive a generated descriptor as fresh SQL authority.
	forged := *owner
	forged.Text = strings.Replace(owner.Text, "self.Warning>", "self.StaleWarning>", 1)
	forged.Types, err = freshBorrowedForeignTypes(t.Context(), &forged, forged.Text)
	require.NoError(t, err)
	var deps *borrowedOutputDependencies
	_, err = freshBorrowedForeignTypes(t.Context(), &forged, forged.Text, &deps)
	require.NoError(t, err)
	require.Empty(t, deps.names)
	// Full fresh owner planning must still reject a generated-only output DTO.
	require.NoError(t, os.WriteFile(owner.Path, []byte(forged.Text), 0600))
	freshChild := *child
	freshChild.dependencySnapshot = nil
	freshChild.preparation = nil
	_, err = (Generator{Operation: "patch"}).Generate(t.Context(), GenerationRequest{Source: &freshChild, Destination: root})
	require.ErrorContains(t, err, "StaleWarning")
	require.NoError(t, os.WriteFile(owner.Path, []byte(owner.Text), 0600))
	// SQL output/derived outputs and emitted body/view values do not seed DTO authority.
	for _, excludedBinding := range []string{"output/view", "output/derived", "output/summary", "body/data", "view/current"} {
		text := strings.Replace(owner.Text, "("+binding+")", "("+excludedBinding+").Output()", 1)
		prepared := dql.PrepareSource(text)
		require.NoError(t, prepared.Err())
		excluded, err := borrowedAuthoredOutputs(owner, prepared, filepath.Join(root, "generated"), owner.Types)
		require.NoError(t, err)
		require.Empty(t, excluded.names, excludedBinding)
	}

}
