// factoryComposition admits only a root that is the exact generated body type
// backed by the selected source declaration. Every containment edge is checked
// against the same parsed Go source snapshot used by source-member generation.
func factoryComposition(component *spec.Component, prepared *dql.PreparedSource, ownership *factoryDeclarations, resolver *typecatalog.Resolver) (*authoring.FactoryComposition, error) {
	parsed, err := sqlparser.ParseQuery(prepared.SQL)
	if err != nil {
		return nil, err
	}
	// A projection without FROM is not a source-backed logical body. Leave it
	// to the ordinary factory SQL validation instead of stringifying a nil node.
	if parsed == nil || parsed.From.X == nil {
		return nil, nil
	}
	rootSource := strings.TrimSpace(sqlparser.Stringify(parsed.From.X))
	if strings.Contains(rootSource, ".") || rootSource == "" {
		return nil, nil
	}
	var body *spec.Parameter
	plan := &gen.Plan{Package: prepared.TypeContext.PackagePath, Imports: prepared.TypeContext.Imports}
	for _, parameter := range component.Parameters {
		if parameter != nil && strings.EqualFold(parameter.Source.Kind, "body") {
			if body != nil {
				return nil, fmt.Errorf("factory composition requires one body parameter")
			}
			body = parameter
		}
	}
	if body == nil {
		return nil, nil
	}
	bodyCanonical, err := plan.CanonicalType(plan.Package, body.TypeExpr)
	if err != nil {
		return nil, err
	}
	rootCanonical := plan.Package + "." + rootSource
	if bodyCanonical != "*"+rootCanonical && bodyCanonical != "[]*"+rootCanonical {
		if component.Settings.Generation != nil && component.Settings.Generation.SourceInput != "" {
			if err := ownership.load(); err != nil {
				return nil, err
			}
			if len(ownership.types[rootSource]) != 0 {
				return nil, fmt.Errorf("factory logical root differs from source body binding")
			}
		}
		return nil, nil
	}
	if component.Settings.Generation.SourceInput == "" {
		return nil, fmt.Errorf("factory logical root requires source_input authority")
	}
	lookup, err := factorySourceLookup(ownership, resolver)
	if err != nil {
		return nil, err
	}
	rootDescriptor, err := lookup(rootCanonical)
	if err != nil || rootDescriptor == nil {
		return nil, fmt.Errorf("factory logical root lacks selected source declaration: %v", err)
	}
	if rootDescriptor.SynteticType == nil || rootDescriptor.SynteticType.TypeSpec == nil {
		return nil, fmt.Errorf("factory logical root requires original source AST")
	}
	rootDeclarations := ownership.types[rootSource]
	if len(rootDeclarations) != 1 || !rootDeclarations[0].concreteStruct {
		return nil, fmt.Errorf("factory logical root requires one authored concrete source declaration")
	}

	// A combined selected source destination becomes generated after its first
	// successful publication. Reuse that same-owner source snapshot; destination
	// admission and source-member publication still validate its exact ownership.
	if declaration := rootDeclarations[0]; declaration.generated {
		if !ownership.selectedSourceDeclaration(rootSource, declaration.file, declaration) ||
			!strings.HasPrefix(declaration.source, "// Code generated by Datly for "+component.Name+"; DO NOT EDIT.\n") {
			return nil, fmt.Errorf("factory logical root generated source differs from selected owner")
		}
	}

	sourceInput, err := plan.CanonicalType(plan.Package, component.Settings.Generation.SourceInput)
	if err != nil {
		return nil, err
	}
	inputDescriptor, err := lookup(sourceInput)
	if err != nil {
		return nil, err
	}
	inputFields, err := xshape.New(inputDescriptor, lookup).Fields()
	if err != nil {
		return nil, err
	}
	bodyMatches := 0
	for _, field := range inputFields {
		if field.Name != body.Name || !field.Exported {
			continue
		}
		canonical, err := factoryCanonicalIdentityFromField(field, lookup)
		if err != nil {
			return nil, err
		}
		if canonical == bodyCanonical {
			bodyMatches++
		}
	}
	if bodyMatches != 1 {
		return nil, fmt.Errorf("factory body binding differs from selected source_input field")
	}

	type declaration struct{ typ, holder string }
	declarations := map[string]declaration{}
	for _, item := range parsed.List {
		call, ok := item.Expr.(*expr.Call)
		if !ok || !strings.EqualFold(sqlparser.Stringify(call.X), "type") {
			continue
		}
		if len(call.Args) < 2 || len(call.Args) > 3 {
			return nil, fmt.Errorf("invalid factory composition type directive")
		}
		alias := strings.TrimSpace(sqlparser.Stringify(call.Args[0]))
		typ, ok := call.Args[1].(*expr.Literal)
		if !ok {
			return nil, fmt.Errorf("factory type must be literal")
		}
		d := declaration{typ: strings.Trim(typ.Value, "\"'")}
		if len(call.Args) == 3 {
			holder, ok := call.Args[2].(*expr.Literal)
			if !ok {
				return nil, fmt.Errorf("factory holder must be literal")
			}
			d.holder = strings.Trim(holder.Value, "\"'")
		}
		if _, duplicate := declarations[alias]; duplicate {
			return nil, fmt.Errorf("duplicate factory composition type for %s", alias)
		}
		declarations[alias] = d
	}
	rootAlias := parsed.From.Alias
	if rootAlias == "" {
		rootAlias = rootSource
	}
	if declarations[rootAlias].typ != rootSource {
		return nil, fmt.Errorf("logical root must declare exact source body type")
	}
	proof := &authoring.FactoryComposition{RootSource: rootSource, RootAlias: rootAlias, RootType: rootSource}
	type occurrence struct{ typ, path string }
	occurrences := map[string]occurrence{rootAlias: {typ: rootCanonical, path: body.Name}}
	seenPaths := map[string]bool{body.Name: true}
	for _, join := range parsed.Joins {
		if join == nil {
			return nil, fmt.Errorf("nil factory composition join")
		}
		authoredSource := strings.TrimSpace(sqlparser.Stringify(join.With))
		alias := join.Alias
		decl := declarations[alias]
		if alias == "" || occurrences[alias].typ != "" || decl.typ == "" {
			return nil, fmt.Errorf("factory composition join requires unique alias and exact type")
		}
		canonical, err := plan.CanonicalType(plan.Package, decl.typ)
		if err != nil {
			return nil, err
		}
		canonical, err = factoryCanonicalIdentity(canonical, lookup)
		if err != nil {
			return nil, err
		}
		candidates := []authoring.FactoryCompositionJoin{}
		candidateOccurrences := []occurrence{}
		logicalParent, member, logical := strings.Cut(authoredSource, ".")
		if logical {
			// Exact containment alone does not make a native SQLX row logical.
			// Its existing physical mappings require independent owner/table
			// admission, even when the authored join uses a Go member spelling.
			descriptor, err := lookup(canonical)
			if err != nil {
				return nil, err
			}
			fields, err := xshape.New(descriptor, lookup).Fields()
			if err != nil {
				return nil, err
			}
			for _, field := range fields {
				mapping := sqlio.ParseTag(field.Tag)
				if field.Exported && !mapping.Transient && mapping.Column != "" {
					return nil, fmt.Errorf("factory composition member %s has native physical mappings and requires an independently authored physical owner occurrence", alias)
				}
			}
		}
		for parentAlias, parent := range occurrences {
			if logical && logicalParent != parentAlias {
				continue
			}
			descriptor, err := lookup(parent.typ)
			if err != nil {
				return nil, err
			}
			fields, err := xshape.New(descriptor, lookup).Fields()
			if err != nil {
				return nil, err
			}
			for _, field := range fields {
				if !field.Exported || field.Anonymous || (logical && field.Name != member) || (!logical && field.Name != decl.holder) {
					continue
				}
				identity, err := factoryCanonicalIdentityFromField(field, lookup)
				if err != nil {
					return nil, err
				}
				cardinality := spec.CardinalityOne
				if strings.HasPrefix(identity, "[]") {
					cardinality = spec.CardinalityMany
					identity = strings.TrimPrefix(identity, "[]")
				}
				if !strings.HasPrefix(identity, "*") {
					continue
				}
				identity = strings.TrimPrefix(identity, "*")
				if identity != canonical {
					continue
				}
				path := parent.path + "/" + field.Name
				candidate := authoring.FactoryCompositionJoin{Source: authoredSource, Alias: alias, ParentAlias: parentAlias, Holder: field.Name, TypeName: decl.typ, Cardinality: cardinality, Logical: logical}
				if !logical {
					physical, err := factoryPhysicalCompositionJoin(component, path, authoredSource, alias, parentAlias, field.Name, func() string {
						if cardinality == spec.CardinalityMany {
							return "[]*" + canonical
						}
						return "*" + canonical
					}(), cardinality)
					if err != nil {
						continue
					}
					candidate = *physical
					candidate.TypeName = decl.typ
				}
				candidate.Tag = string(field.Tag)
				candidates = append(candidates, candidate)
				candidateOccurrences = append(candidateOccurrences, occurrence{typ: canonical, path: path})
			}
		}
		if len(candidates) != 1 {
			return nil, fmt.Errorf("factory composition join %s has %d selected source member matches", alias, len(candidates))
		}
		selected := candidateOccurrences[0]
		if seenPaths[selected.path] {
			return nil, fmt.Errorf("duplicate factory composition occurrence %s", selected.path)
		}
		for _, prior := range occurrences {
			if prior.typ == selected.typ && strings.HasPrefix(selected.path, prior.path+"/") {
				return nil, fmt.Errorf("cyclic factory composition at %s", selected.path)
			}
		}
		seenPaths[selected.path] = true
		occurrences[alias] = selected
		proof.Joins = append(proof.Joins, candidates[0])
	}
	return proof, nil
}

func factoryCanonicalIdentityFromField(field xshape.Field, lookup xshape.Lookup) (string, error) {
	canonical, err := field.CanonicalType()
	if err != nil {
		return "", err
	}
	return factoryCanonicalIdentity(canonical, lookup)
}

// Only the existing source-member composition classifier can mint this exact
// occurrence set. Imported native owner graphs retain physical marker rules.
func factoryCompositionOccurrences(proof *authoring.FactoryComposition, root *spec.View) (map[string]gen.CompositionOccurrence, error) {
	if proof == nil {
		return nil, nil
	}
	result := map[string]gen.CompositionOccurrence{}
	visiting := map[*spec.View]bool{}
	var visit func(*spec.View) error
	visit = func(view *spec.View) error {
		if view == nil || visiting[view] {
			return fmt.Errorf("factory composition occurrence graph incomplete or cyclic")
		}
		visiting[view] = true
		defer delete(visiting, view)
		if proof.Logical(view) {
			identity, err := view.Identity()
			if err != nil {
				return err
			}
			if _, exists := result[identity]; exists {
				return fmt.Errorf("duplicate factory composition occurrence %s", identity)
			}
			result[identity] = gen.CompositionOccurrence{TypeName: view.TypeName, Cardinality: view.Cardinality}
		}
		for _, relation := range view.Relations {
			if relation == nil {
				return fmt.Errorf("factory composition relation incomplete")
			}
			if err := visit(relation.View); err != nil {
				return err
			}
		}
		return nil
	}
	if err := visit(root); err != nil {
		return nil, err
	}
	return result, nil
}
