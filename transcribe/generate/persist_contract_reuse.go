package generate

import (
	"fmt"
	"path/filepath"
	"strings"
)

type contractArtifactProposal struct {
	content  string
	role     string
	typeName string
}

// Only a source-less generated POST factory's own planned contract artifacts
// may be reused. Other generated products retain ordinary collision ownership.
func (p *scaffoldPersistence) prepareContractProposals(target string) error {
	if p.contractProposals != nil {
		return nil
	}
	p.contractProposals = map[string]contractArtifactProposal{}
	plan := p.plan
	if plan == nil || plan.ExternalHandler == nil || plan.ExternalHandler.Build == nil || plan.ExternalHandler.Package != plan.Package || !plan.ExternalHandler.GeneratedContracts || plan.ExternalHandler.InputShape != nil || len(plan.Views) != 0 || plan.MutationHandler != nil || plan.Input.Ownership != ContractGenerated || plan.Output.Ownership != ContractGenerated || !plan.localShape(plan.Input.Package) || !plan.localShape(plan.Output.Package) {
		return nil
	}
	if len(plan.Routes) == 0 {
		return nil
	}
	for _, route := range plan.Routes {
		if route.Method != "POST" {
			return nil
		}
	}
	roles := map[string]contractArtifactProposal{
		filepath.Clean(plan.Input.Destination):                                    {role: "input", typeName: plan.Input.Type},
		filepath.Clean(plan.Output.Destination):                                   {role: "output", typeName: plan.Output.Type},
		filepath.Clean(plan.Generation.File("input_setters", "input_setters.go")): {role: "input_setters", typeName: plan.Input.Type},
	}
	// A destination carrying another product cannot be partially claimed.
	for _, generated := range plan.GeneratedTypes {
		delete(roles, filepath.Clean(generated.Destination))
	}
	if plan.EntitySupport != nil {
		delete(roles, filepath.Clean(plan.EntitySupport.Destination))
	}
	if plan.Resources != nil {
		delete(roles, filepath.Clean(plan.Resources.Destination))
	}
	delete(roles, filepath.Clean(plan.RouterDest))
	if plan.FactoryLink != nil {
		delete(roles, filepath.Clean(plan.FactoryLink.Destination))
	}
	for _, file := range p.files {
		name, err := managedPath(target, file.Path)
		if err != nil {
			return err
		}
		if proposal, ok := roles[name]; ok {
			proposal.content = file.Content
			p.contractProposals[name] = proposal
		}
	}
	return nil
}

// Normalize exactly the known owner header and Input/Output scaffold line.
// All other bytes, including comments, build directives, tags and bodies, matter.
func normalizedContractArtifact(content string, proposal contractArtifactProposal) (string, error) {
	lines := strings.Split(content, "\n")
	const prefix = "// Code generated by Datly for "
	const suffix = "; DO NOT EDIT."
	if len(lines) == 0 || !strings.HasPrefix(lines[0], prefix) || !strings.HasSuffix(lines[0], suffix) {
		return "", fmt.Errorf("unrecognized generated contract provenance")
	}
	owner := strings.TrimSuffix(strings.TrimPrefix(lines[0], prefix), suffix)
	if owner == "" || strings.Contains(owner, ";") {
		return "", fmt.Errorf("malformed generated contract owner")
	}
	lines[0] = prefix + "<contract-owner>" + suffix
	if proposal.role == "input" || proposal.role == "output" {
		expected := "// " + proposal.typeName + " is the generated " + proposal.role + " scaffold for " + owner + "."
		count := 0
		for i, line := range lines {
			if line == expected {
				lines[i] = "// " + proposal.typeName + " is the generated " + proposal.role + " scaffold for <contract-owner>."
				count++
			}
		}
		if count != 1 {
			return "", fmt.Errorf("unrecognized generated %s scaffold provenance", proposal.role)
		}
	}
	return strings.Join(lines, "\n"), nil
}

func (p *scaffoldPersistence) retainEquivalentContract(target, name string, current []byte) error {
	proposal, ok := p.contractProposals[name]
	if !ok {
		return fmt.Errorf("artifact is not a reusable native factory contract")
	}
	expected, err := normalizedContractArtifact(proposal.content, proposal)
	if err != nil {
		return err
	}
	actual, err := normalizedContractArtifact(string(current), proposal)
	if err != nil {
		return err
	}
	if actual != expected {
		return fmt.Errorf("generated %s contract differs from independently rendered proposal", proposal.role)
	}
	for i, file := range p.files {
		relative, err := managedPath(target, file.Path)
		if err != nil {
			return err
		}
		if relative == name {
			p.files[i].Content = string(current)
			p.retainedContracts[name] = string(current)
			return nil
		}
	}
	return fmt.Errorf("reusable contract proposal is missing")
}

// A collision is eligible only when its retained source remains selected in the
// final package context. File equality cannot authorize an excluded artifact.
func (p *scaffoldPersistence) validateRetainedContractSelection(target, readRoot string) error {
	if len(p.retainedContracts) == 0 {
		return nil
	}
	files, err := scaffoldBuildFiles(target, readRoot)
	if err != nil {
		return err
	}
	for _, file := range p.files {
		relative, err := managedPath(target, file.Path)
		if err != nil {
			return err
		}
		files[filepath.Join(target, relative)] = []byte(file.Content)
	}
	for relative := range p.renames {
		files[filepath.Join(target, relative)] = nil
	}
	selected, err := p.plan.stagedBuild().GoFiles(p.plan.Package, files)
	if err != nil {
		return err
	}
	active := map[string]bool{}
	for _, name := range selected {
		active[name] = true
	}
	for name := range p.retainedContracts {
		if !active[name] {
			return fmt.Errorf("reusable generated contract %s is not build-selected", name)
		}
	}
	return nil
}
