package generate

import (
	"encoding/json"
	"github.com/viant/datly/internal/readergraph"
	"github.com/viant/datly/spec"
	"strings"
	"testing"
	"testing/fstest"
)

func TestReaderMetadataRequiresCurrentGeneratedOwnership(t *testing.T) {
	const uri = "records:metadata/records_reader.json"
	p := &Plan{Package: "example.com/records", ComponentName: "Records", Holder: "RecordsComponent", Input: ContractPlan{DescriptorKey: "example.com/records.Input"}, Output: ContractPlan{DescriptorKey: "example.com/records.Output"}}
	d := readergraph.Document{ABI: strings.Repeat("a", 64), Version: 1, Package: p.Package, Holder: p.Holder, Field: "Contract", Input: p.Input.DescriptorKey, Output: p.Output.DescriptorKey, Component: &spec.Component{Name: "Records"}}
	body, err := json.Marshal(d)
	if err != nil {
		t.Fatal(err)
	}
	header := "// Code generated by Datly for Records; DO NOT EDIT.\n"
	holder := header + "package records\ntype RecordsComponent struct {Contract any `component:\"Records,readerMetadata=" + uri + "\"`}\n"
	resources := header + "package records\nimport \"embed\"\nconst ResourcesDatlyResourceNamespace=\"records\"\n//go:embed metadata/records_reader.json\nvar ResourcesDatlyResources embed.FS\n"
	source := fstest.MapFS{"router.go": {Data: []byte(holder)}, "resources.go": {Data: []byte(resources)}, "metadata/records_reader.json": {Data: body}}
	if _, err = readerMetadataOwned(source, p, &ResourcePlan{Namespace: "records"}, uri); err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct{ name, file, old, new string }{
		{"copied document", "router.go", header, ""},
		{"application embed", "resources.go", header, ""},
		{"stale holder", "router.go", "RecordsComponent", "PreviousComponent"},
		{"foreign embed", "resources.go", "metadata/records_reader.json", "metadata/other.json"},
		{"stale nominal", "metadata/records_reader.json", "example.com/records.Output", "example.com/records.PreviousOutput"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			copy := fstest.MapFS{}
			for k, v := range source {
				copy[k] = &fstest.MapFile{Data: append([]byte(nil), v.Data...)}
			}
			copy[tc.file].Data = []byte(strings.Replace(string(copy[tc.file].Data), tc.old, tc.new, 1))
			if _, err := readerMetadataOwned(copy, p, &ResourcePlan{Namespace: "records"}, uri); err == nil {
				t.Fatal("unowned metadata accepted")
			}
		})
	}
}
