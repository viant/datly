func TestGeneratedHelperSelectedSourceOwnership(t *testing.T) {
	source, root := stockExpandedCurrentFixture(t, "absent-physical-current")
	ctx := context.Background()
	if _, err := (Generator{Operation: "patch"}).Generate(ctx, GenerationRequest{Source: source, Destination: root}); err != nil {
		t.Fatal(err)
	}
	const pkg = "github.com/viant/datly/stockcurrentfixture/generated"
	writeSourceFile(t, root, "generated/key_helpers.go", "// Code generated by Datly for Probe; DO NOT EDIT.\npackage generated\ntype KeysRow struct { Id *int }\n")
	writeSourceFile(t, root, "generated/foreign_helpers.go", "// Code generated by Datly for Other; DO NOT EDIT.\npackage generated\ntype ForeignProjection struct { Id *int }\n")
	writeSourceFile(t, root, "generated/authored_helpers.go", "package generated\ntype AuthoredProjection struct { Id *int }\n")
	writeSourceFile(t, root, "source/probe.dql", "#import('generated','"+pkg+"')\n"+source.Text)
	project, err := (&Discovery{BaseDir: root, Include: []string{"github.com/viant/datly/stockcurrentfixture/source"}, SourceFile: "probe.dql", Connector: "main", ColumnRefiner: source.ColumnRefiner}).Compile(ctx)
	if err != nil {
		t.Fatal(err)
	}
	compiled := project.Components[0]
	for _, tc := range []struct {
		name, row, explicit, output, tag, header string
		inferred                                 bool
	}{
		{name: "owned projection", row: "KeysRow", inferred: true},
		{name: "explicit type", row: "KeysRow", explicit: "[]KeysRow"},
		{name: "explicit output type", row: "KeysRow", output: "[]KeysRow"},
		{name: "explicit type name", row: "KeysRow", tag: `typeName:"KeysRow"`},
		{name: "foreign component same inferred name", row: "KeysRow", header: "// Code generated by Datly for Other; DO NOT EDIT.\n"},
		{name: "authored source same inferred name", row: "KeysRow", header: " "},
		{name: "noninferred generated type", row: "ForeignProjection"},
		{name: "authored source", row: "AuthoredProjection"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if tc.header != "" {
				writeSourceFile(t, root, "generated/key_helpers.go", tc.header+"package generated\ntype KeysRow struct { Id *int }\n")
				defer writeSourceFile(t, root, "generated/key_helpers.go", "// Code generated by Datly for Probe; DO NOT EDIT.\npackage generated\ntype KeysRow struct { Id *int }\n")
			}
			component := compiled.Component.Clone()
			p := &spec.Parameter{Name: "Keys", Source: spec.BindSource{Kind: "param", Name: "Probe"}, TypeExpr: "[]" + tc.row, Codec: &spec.Codec{Body: "structql", Args: []string{"uri=queries/keys.sql"}}}
			component.Parameters = []*spec.Parameter{p}
			authored := &spec.Component{Parameters: []*spec.Parameter{{Name: p.Name, Source: p.Source, TypeExpr: tc.explicit, OutputTypeExpr: tc.output, Tag: tc.tag}}}
			// Package bootstrap retains codec URIs, not DeclarationSQL. Generation
			// supplies the parsed replacement projection after appendProjection.
			owned, err := generatedHelperAuthority(ctx, compiled.Source, component, authored, compiled.TypeResolver)
			if err != nil {
				t.Fatal(err)
			}
			restoreInferredHelpers(component, owned, gen.Declarations{p.Identity(): {Projection: []gen.DeclarationProjection{{Name: "Id", Source: "Id"}}}})

			if (p.TypeExpr == "") != tc.inferred {
				t.Fatalf("type=%q inferred=%v", p.TypeExpr, tc.inferred)
			}
			if tc.inferred {
				minimal := &spec.Component{Name: "Probe", RootView: &spec.View{Name: "Probe", Columns: []*spec.Column{{Name: "Id", Type: spec.TypeRef{Name: "int"}}}}, Parameters: []*spec.Parameter{{Name: "Probe", Source: spec.BindSource{Kind: "body", Name: "data"}, TypeExpr: "[]*ProbeView"}, p}}
				planned, err := gen.New(gen.Input{Component: minimal, TargetPackage: pkg, PackageName: "generated", Declarations: gen.Declarations{p.Identity(): {Projection: []gen.DeclarationProjection{{Name: "Id", Source: "Id"}}}}}).Plan()
				if err != nil {
					t.Fatal(err)
				}
				if len(planned.HelperTypes) != 1 || planned.HelperTypes[0].Name != "KeysRow" {
					t.Fatalf("retained Input key helper omitted: %+v", planned.HelperTypes)
				}
			}
		})
	}
}

func TestInferredCurrentKeyHelperSurvivesPackageReload(t *testing.T) {
	source, root := stockExpandedCurrentFixture(t, "absent-physical-current")
	source.Text = strings.Replace(source.Text, "#define($_ = $CurrentProbe<?>(view/CurrentProbe).Cardinality('Many') /* SELECT * FROM roots WHERE id=1 */)\n", "", 1)
	ctx := context.Background()
	first, err := (Generator{Operation: "patch"}).Generate(ctx, GenerationRequest{Source: source, Destination: root})
	if err != nil {
		t.Fatal(err)
	}
	helpers := map[string]string{}
	for _, file := range first.Result.Files {
		data, err := os.ReadFile(file.Path)
		if err != nil {
			t.Fatal(err)
		}
		if strings.Contains(string(data), "type ProbeKeysRow struct") {
			helpers[file.Path] = "type ProbeKeysRow struct"
		}
	}
	if len(helpers) == 0 {
		t.Fatal("fixture did not generate inferred Current key helper")
	}
	writeSourceFile(t, root, "source/probe.dql", "#import('generated','github.com/viant/datly/stockcurrentfixture/generated')\n"+source.Text)
	for generation := 2; generation <= 3; generation++ {
		project, err := (&Discovery{BaseDir: root, Include: []string{"github.com/viant/datly/stockcurrentfixture/source"}, SourceFile: "probe.dql", Connector: "main", ColumnRefiner: source.ColumnRefiner}).Compile(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := (Generator{Operation: "patch"}).Generate(ctx, GenerationRequest{Compiled: project.Components[0], Destination: root}); err != nil {
			t.Fatal(err)
		}
		for path, declaration := range helpers {
			data, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(data), declaration) {
				t.Fatalf("generation %d deleted %s", generation, declaration)
			}
		}
	}
}
