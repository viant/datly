package transcribe

import (
	"github.com/viant/datly/spec"
	"github.com/viant/datly/transcribe/dql"
	"go/ast"
	"go/parser"
	"go/token"
	"strings"
	"testing"
)

func TestFactoryCompositionSelectedSourceMembers(t *testing.T) {
	source := `package fixture
 type Input struct { Body *RouteBody }
 type RouteBody struct { Data []*Campaign }
 type Alias = Campaign
 type Campaign struct { IDs []int }
 type Wrong struct { IDs []int }
 `
	fixture := func(text, sql string) (bool, error) {
		tree, err := parser.ParseFile(token.NewFileSet(), "source.go", text, 0)
		if err != nil {
			t.Fatal(err)
		}
		ownership := &factoryDeclarations{pkg: "example.test/fixture", sourceMembers: []spec.SourceMember{{Owner: "RouteBody", Name: "cache"}}, types: map[string][]factoryDeclaration{}}
		for _, decl := range tree.Decls {
			if generic, ok := decl.(*ast.GenDecl); ok {
				for _, entry := range generic.Specs {
					if typ, ok := entry.(*ast.TypeSpec); ok {
						_, structure := typ.Type.(*ast.StructType)
						ownership.types[typ.Name.Name] = append(ownership.types[typ.Name.Name], factoryDeclaration{typeSpec: typ, concreteStruct: structure, file: "source.go", source: text, generated: strings.HasPrefix(text, "// Code generated ")})
					}
				}
			}
		}
		component := &spec.Component{Name: "Fixture", Settings: &spec.Settings{Generation: &spec.GenerationSettings{SourceInput: "Input"}}, Parameters: []*spec.Parameter{{Name: "Body", TypeExpr: "*RouteBody", Source: spec.BindSource{Kind: "body"}}}}
		prepared := dql.PrepareSource(sql)
		prepared.TypeContext = &spec.TypeContext{PackagePath: ownership.pkg}
		proof, err := factoryComposition(component, prepared, ownership, nil)
		return proof != nil, err
	}
	sql := `SELECT type(rb,'RouteBody'),type(n0,'Campaign','Data'), n0.IDs, CAST(n0.IDs AS '[]int') FROM RouteBody rb CROSS JOIN rb.Data n0`
	if ok, err := fixture(source, sql); err != nil || !ok {
		t.Fatalf("selected source rejected: %v", err)
	}
	if ok, err := fixture(strings.Replace(source, "Data []*Campaign", "Data []*Alias", 1), sql); err != nil || !ok {
		t.Fatalf("real alias rejected: %v", err)
	}
	if ok, err := fixture("// Code generated by Datly for Fixture; DO NOT EDIT.\n"+source, sql); err != nil || !ok {
		t.Fatalf("same-owner selected regeneration rejected: %v", err)
	}
	if _, err := fixture("// Code generated by Datly for Other; DO NOT EDIT.\n"+source, sql); err == nil {
		t.Fatal("foreign generated root accepted")
	}
	physicalSource := strings.Replace(source, "type Campaign struct { IDs []int }", "type Campaign struct { IDs []int `sqlx:\"ID\"` }", 1)
	if _, err := fixture(physicalSource, sql); err == nil || !strings.Contains(err.Error(), "native physical mappings") {
		t.Fatalf("physical row disguised as logical accepted: %v", err)
	}
	for _, text := range []string{strings.Replace(source, "Data []*Campaign", "Data []*Wrong", 1), strings.Replace(source, "Data []*Campaign", "Other []*Campaign", 1), strings.Replace(source, "Body *RouteBody", "Body []*RouteBody", 1), strings.Replace(source, "Data []*Campaign", "Data []Campaign", 1)} {
		if _, err := fixture(text, sql); err == nil {
			t.Fatalf("unproved member accepted: %s", text)
		}
	}
}
