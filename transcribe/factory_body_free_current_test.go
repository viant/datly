func TestFactoryBodyFreeAuthoredCurrent(t *testing.T) {
	for _, spelling := range []string{"Marker", "archive.Marker", handlerFixtureModule + "/archive.Marker", "shared.Marker"} {
		t.Run(spelling, func(t *testing.T) {
			root, source := generatedPostFactoryFixture(t)
			writeSourceHandlerFile(t, root, "archive/business.go", `package archive
import("context";"github.com/viant/xdatly/handler")
type Handler struct{}
func NewArchive() handler.Contract[ArchiveInput,ArchiveOutput] {return &Handler{}}
func (*Handler) Exec(_ context.Context,_ handler.Session,in *ArchiveInput,out *ArchiveOutput) error {out.Status="ok";return nil}
`)
			authored := `package archive
type Marker struct { Id int ` + "`sqlx:\"ID\"`" + `; Owner int ` + "`sqlx:\"OWNER\"`" + `; Has *MarkerHas ` + "`setMarker:\"true\" sqlx:\"-\" json:\"-\"`" + ` }
type MarkerHas struct { Id, Owner bool }
`
			rowPath := "archive/marker.go"
			if spelling == "shared.Marker" {
				rowPath = "shared/marker.go"
				authored = strings.Replace(authored, "package archive", "package shared", 1)
				source.Text = strings.Replace(source.Text, "#setting", "#import('shared','"+handlerFixtureModule+"/shared')\n#setting", 1)
			}
			writeSourceHandlerFile(t, root, rowPath, authored)
			resultType := "archive.Marker"
			if spelling == "shared.Marker" {
				resultType = spelling
			}
			source.Text = strings.ReplaceAll(source.Text, "archive.ResultItem", resultType)
			source.Text = strings.Replace(source.Text, "#define($_ = $Data<*archive.ArchiveRequest>(body/data).Optional())", `#define($_ = $Current<[]*`+spelling+`>(view/Current).Cardinality('Many') /* SELECT ID,OWNER FROM RECORDS */)
#define($_ = $Candidates<?>(view/Candidates).Cardinality('Many').TypeName('Candidate') /* SELECT * FROM CANDIDATES */)`, 1)
			db, err := sql.Open("sqlite3", filepath.Join(t.TempDir(), "read.db"))
			require.NoError(t, err)
			defer db.Close()
			_, err = db.Exec("CREATE TABLE RECORDS(ID INTEGER PRIMARY KEY,OWNER INTEGER NOT NULL); CREATE TABLE CANDIDATES(ID INTEGER NOT NULL)")
			require.NoError(t, err)
			source.Connector = "fixture"
			source.Text = strings.Replace(source.Text, "#setting", "#setting($_ = $connector('fixture'))\n#setting", 1)
			source.ColumnRefiner = column.New(column.Connections{"fixture": db})
			var stable map[string]string
			for round := 0; round < 3; round++ {
				if round == 2 {
					_, err = db.Exec("ALTER TABLE CANDIDATES ADD COLUMN EXTRA TEXT")
					require.NoError(t, err)
				}
				compiled, err := (&Discovery{BaseDir: root, GoBuild: source.GoBuild, ColumnRefiner: source.ColumnRefiner}).CompileSource(t.Context(), source)
				require.NoError(t, err)
				require.Nil(t, compiled.Component.RootView)
				require.Nil(t, compiled.ExternalHandler.InputShape)
				require.Len(t, compiled.Component.Views, 2)
				request := GenerationRequest{Compiled: compiled, Destination: root}
				if round == 1 {
					request = GenerationRequest{Source: compiled.Source, Destination: root}
				}
				generated, err := (Generator{Operation: "post"}).Generate(t.Context(), request)
				require.NoError(t, err)
				linked := 0
				for _, view := range generated.Result.Plan.Views {
					if strings.HasSuffix(view.Type, ".Marker") || view.Type == "Marker" {
						require.Equal(t, gen.ViewLinked, view.Ownership)
						require.Empty(t, view.Destination)
						linked++
					}
				}
				require.Equal(t, 1, linked)
				actual, err := os.ReadFile(filepath.Join(root, rowPath))
				require.NoError(t, err)
				require.Equal(t, authored, string(actual))
				snapshot := sourceHandlerSnapshot(t, root)
				if round == 0 {
					stable = snapshot
				}
				if round == 1 {
					require.Equal(t, stable, snapshot)
				}
				if round == 2 {
					require.NotEqual(t, stable, snapshot, "generated wildcard row evolves independently")
				}
			}
		})
	}
}

func TestFactoryBodyFreeCurrentOwnershipAndAuthorityFailures(t *testing.T) {
	for _, tc := range []struct{ name, expression, options, row string }{
		{name: "stale generated", expression: "[]*archive.Marker", row: "// Code generated by Datly for Previous; DO NOT EDIT.\n"},
		{name: "missing type", expression: "[]*archive.Missing"},
		{name: "one cardinality", expression: "[]*archive.Marker", options: ".Cardinality('One')"},
		{name: "wrong wrapper", expression: "*archive.Marker", options: ".Cardinality('Many')"},
		{name: "type conflict", expression: "[]*archive.Marker", options: ".TypeName('Other')"},
		{name: "output wrapper conflict", expression: "[]*archive.Marker,*archive.Marker"},
		{name: "destination", expression: "[]*archive.Marker", options: ".Dest('marker.go')"},
		{name: "column mismatch", expression: "[]*archive.Marker", row: "incompatible"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			root, source := generatedPostFactoryFixture(t)
			business := `package archive
import("context";"github.com/viant/xdatly/handler")
type Handler struct{}
func NewArchive() handler.Contract[ArchiveInput,ArchiveOutput] {return &Handler{}}
func (*Handler) Exec(_ context.Context,_ handler.Session,in *ArchiveInput,out *ArchiveOutput)error{return nil}
`
			writeSourceHandlerFile(t, root, "archive/business.go", business)
			row := `package archive
type Marker struct { Id int ` + "`sqlx:\"ID\"`" + `; Owner int ` + "`sqlx:\"OWNER\"`" + ` }
`
			if tc.row == "incompatible" {
				row = strings.Replace(row, "Owner int", "Owner []int", 1)
			} else {
				row = tc.row + row
			}
			writeSourceHandlerFile(t, root, "archive/marker.go", row)
			source.Text = strings.ReplaceAll(source.Text, "archive.ResultItem", "archive.Marker")
			source.Text = strings.Replace(source.Text, "#define($_ = $Data<*archive.ArchiveRequest>(body/data).Optional())", `#define($_ = $Current<`+tc.expression+`>(view/Current)`+tc.options+` /* SELECT ID,OWNER FROM RECORDS */)`, 1)
			if tc.row == "incompatible" {
				source.Text = strings.Replace(source.Text, "SELECT ID,OWNER FROM RECORDS", "SELECT r.*,CAST(r.OWNER AS int) FROM RECORDS r", 1)
			}
			source.Text = strings.Replace(source.Text, "#setting", "#setting($_ = $connector('fixture'))\n#setting", 1)
			db, err := sql.Open("sqlite3", filepath.Join(t.TempDir(), "read.db"))
			require.NoError(t, err)
			defer db.Close()
			_, err = db.Exec("CREATE TABLE RECORDS(ID INTEGER PRIMARY KEY,OWNER INTEGER NOT NULL)")
			require.NoError(t, err)
			source.ColumnRefiner = column.New(column.Connections{"fixture": db})
			before := sourceHandlerSnapshot(t, root)
			compiled, err := (&Discovery{BaseDir: root, GoBuild: source.GoBuild, ColumnRefiner: source.ColumnRefiner}).CompileSource(t.Context(), source)
			if err == nil {
				_, err = (Generator{Operation: "post"}).Generate(t.Context(), GenerationRequest{Compiled: compiled, Destination: root})
			}
			require.Error(t, err)
			require.Equal(t, before, sourceHandlerSnapshot(t, root))
		})
	}
}
