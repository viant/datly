func TestBorrowedOwnerRetainsAuthoredScalar(t *testing.T) {
	root, owner, child, _ := borrowedAuxiliaryOwnerFixture(t)
	scalar := filepath.Join(root, "generated", "mode.go")
	methods := filepath.Join(root, "generated", "mode_json.go")
	writeSourceFile(t, root, "generated/mode.go", "package generated\ntype Mode int\ntype Unrelated struct { Value int }\n")
	writeSourceFile(t, root, "generated/mode_excluded.go", "//go:build datly_excluded_scalar\n\npackage generated\nfunc(*Mode)Excluded(){}\n")
	writeSourceFile(t, root, "generated/mode_test.go", "package generated\nfunc(*Mode)TestOnly(){}\n")
	methodSource := "package generated\nfunc(m *Mode)UnmarshalJSON([]byte)error{*m=7;return nil}\n"
	writeSourceFile(t, root, "generated/mode_json.go", methodSource)
	writeSourceFile(t, root, "generated/forged_scalar.go", "// Code generated by Datly for Forged; DO NOT EDIT.\npackage generated\ntype ForgedScalar int\n")
	scalarBefore, err := os.ReadFile(scalar)
	require.NoError(t, err)
	for _, source := range []*Source{owner, child} {
		source.Text = strings.Replace(source.Text, "NULL AS note", "NULL AS note,NULL AS mode", 1)
		source.Text = strings.Replace(source.Text, "SELECT r.*", "SELECT r.*,CAST(r.mode AS 'self.Mode'),tag(r.mode,'sqlx:\"-\"')", 1)
		require.NoError(t, os.WriteFile(source.Path, []byte(source.Text), 0600))
		source.Types, err = freshBorrowedForeignTypes(t.Context(), source, source.Text)
		require.NoError(t, err)
	}
	for _, name := range []string{"Record", "RecordHas", "Unrelated", "ForgedScalar"} {
		_, found, err := child.Types.Resolve(typecatalog.TranscribeAuthority, "github.com/viant/datly/auxownerfixture/generated."+name)
		require.NoError(t, err)
		require.False(t, found, "owner declaration regained fresh SQL authority: %s", name)
	}
	origin, found, err := child.Types.Origin(typecatalog.TranscribeAuthority, "github.com/viant/datly/auxownerfixture/generated.Mode")
	require.NoError(t, err)
	require.True(t, found)
	require.Equal(t, typecatalog.TypeOriginPackage, origin)
	for _, source := range []*Source{owner, child} {
		_, err = (Generator{Operation: "patch"}).Generate(t.Context(), GenerationRequest{Source: source, Destination: root})
		require.NoError(t, err)
	}
	snapshot := borrowedGeneratedSnapshot(t, root)
	for _, source := range []*Source{owner, child} {
		_, err = (Generator{Operation: "patch"}).Generate(t.Context(), GenerationRequest{Source: source, Destination: root})
		require.NoError(t, err)
	}
	require.Equal(t, snapshot, borrowedGeneratedSnapshot(t, root))
	scalarAfter, err := os.ReadFile(scalar)
	require.NoError(t, err)
	require.Equal(t, scalarBefore, scalarAfter)
	methodsAfter, err := os.ReadFile(methods)
	require.NoError(t, err)
	require.Equal(t, methodSource, string(methodsAfter))
	writeSourceFile(t, root, "generated/scalar_runtime_test.go", `package generated
import("testing";"encoding/json";"reflect")
func TestAuthoredScalarIdentityAndDecoder(t *testing.T){var row Record;if err:=json.Unmarshal([]byte("{\"mode\":\"native\"}"),&row);err!=nil{t.Fatal(err)};if row.Mode!=Mode(7){t.Fatalf("decoder lost: %+v",row)};field,_:=reflect.TypeFor[Record]().FieldByName("Mode");if field.Type!=reflect.TypeFor[Mode](){t.Fatal("named scalar type changed")}}
`)
	borrowedGeneratedModuleTest(t, root)
	compiled, err := NewCompiler().Compile(t.Context(), child)
	require.NoError(t, err)
	var proof *gen.BorrowedRowAuthority
	for _, reference := range compiled.Views {
		if reference != nil && reference.Borrowed != nil {
			proof = reference.Borrowed
		}
	}
	require.NotNil(t, proof)
	require.NoError(t, proof.ValidateFiles(func(path string) string { return path }))
	require.NoError(t, os.WriteFile(methods, []byte(strings.Replace(methodSource, "*m=7", "*m=9", 1)), 0600))
	require.Error(t, proof.ValidateFiles(func(path string) string { return path }), "authored decoder source drift was not sealed")
	require.NoError(t, os.WriteFile(methods, []byte(methodSource), 0600))
	// Revalidation uses captured scalar authority even when the destination moves.
	target := filepath.Join(root, "generated")
	require.NoError(t, os.Rename(target, target+".staged"))
	require.NoError(t, proof.ValidateSchema())
	require.NoError(t, os.Rename(target+".staged", target))
}

func TestBorrowedAuthoredScalarRequiresBuiltinAuthority(t *testing.T) {
	for _, body := range []string{"bool", "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "uintptr", "float32", "float64", "complex64", "complex128", "string", "byte", "rune"} {
		t.Run(body, func(t *testing.T) { require.True(t, borrowedScalarNamesForTest(t, "type Mode "+body)["Mode"]) })
	}
	require.False(t, borrowedScalarNamesForTest(t, "type int struct{ Value bool }; type Mode int")["Mode"])
	require.False(t, borrowedScalarNamesForTest(t, "type string struct{ Value bool }; type Mode string")["Mode"])
}

func borrowedScalarNamesForTest(t *testing.T, declarations string) map[string]bool {
	t.Helper()
	source := "package owned\n" + declarations
	parsed, err := parser.ParseFile(token.NewFileSet(), "mode.go", source, 0)
	require.NoError(t, err)
	file := &smodel.GoFile{Name: "mode.go"}
	for _, decl := range parsed.Decls {
		if group, ok := decl.(*ast.GenDecl); ok {
			for _, spec := range group.Specs {
				if typ, ok := spec.(*ast.TypeSpec); ok {
					file.Types = append(file.Types, &smodel.Type{Name: typ.Name.Name, PkgPath: "example.com/owned", TypeSpec: typ})
				}
			}
		}
	}
	snapshot := &dependency.Snapshot{Packages: map[string]*smodel.Package{"example.com/owned": {PkgPath: "example.com/owned", Types: file.Types, Files: []*smodel.GoFile{file}}}, Files: []gen.BorrowedAuthorityFile{{Path: "/captured/mode.go", Bytes: []byte(source)}}}
	return borrowedAuthoredScalarNames(snapshot, "example.com/owned", "/captured")
}
