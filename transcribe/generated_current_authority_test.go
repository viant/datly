package transcribe

import (
	"context"
	"reflect"
	"testing"

	"github.com/viant/datly/spec"
	"github.com/viant/datly/typecatalog"
	"github.com/viant/x"
)

type generatedCurrentAuthoredRuntimeRow struct{ Id *int }

func TestGeneratedCurrentSelectedSourceOwnershipControls(t *testing.T) {
	source, root := stockExpandedCurrentFixture(t, "absent-physical-current")
	ctx := context.Background()
	if _, err := (Generator{Operation: "patch"}).Generate(ctx, GenerationRequest{Source: source, Destination: root}); err != nil {
		t.Fatal(err)
	}
	const pkg = "github.com/viant/datly/stockcurrentfixture/generated"
	writeSourceFile(t, root, "generated/self_read.go", "// Code generated by Datly for Probe; DO NOT EDIT.\npackage generated\ntype SelfReadRow struct { Id *int }\n")
	writeSourceFile(t, root, "generated/other_read.go", "// Code generated by Datly for Other; DO NOT EDIT.\npackage generated\ntype OtherReadRow struct { Id *int }\n")
	writeSourceFile(t, root, "generated/authored_read.go", "package generated\ntype AuthoredReadRow struct { Id *int }\n")
	writeSourceFile(t, root, "source/probe.dql", "#import('generated','"+pkg+"')\n"+source.Text)
	registry := x.NewRegistry()
	runtimeType := reflect.TypeFor[generatedCurrentAuthoredRuntimeRow]()
	registry.Register(x.NewType(runtimeType, x.WithName("AuthoredReadRow"), x.WithPkgPath(pkg)))
	project, err := (&Discovery{BaseDir: root, Include: []string{"github.com/viant/datly/stockcurrentfixture/source"}, SourceFile: "probe.dql", Connector: "main", ColumnRefiner: source.ColumnRefiner, Registry: registry}).Compile(ctx)
	if err != nil {
		t.Fatal(err)
	}
	compiled := project.Components[0]
	for _, tc := range []struct {
		name   string
		origin typecatalog.TypeOrigin
	}{{"SelfReadRow", typecatalog.TypeOriginGenerated}, {"OtherReadRow", typecatalog.TypeOriginGenerated}, {"AuthoredReadRow", typecatalog.TypeOriginPackage}} {
		resolution, err := compiled.TypeResolver.ResolveWithProvenance(pkg + "." + tc.name)
		if err != nil || resolution == nil || resolution.Origin != tc.origin {
			t.Fatalf("mixed package %s: %+v %v", tc.name, resolution, err)
		}
	}
	descriptor, err := compiled.TypeResolver.Descriptor(pkg + ".AuthoredReadRow")
	if err != nil || descriptor == nil || descriptor.Type != runtimeType {
		t.Fatalf("runtime ReflectType lost: %+v %v", descriptor, err)
	}
	for _, tc := range []struct {
		name, row                             string
		tag                                   string
		viewType                              string
		alias                                 bool
		authored, explicit, borrowed, foreign bool
		own, inherited                        int
	}{
		{name: "same owner generated independent read", row: "SelfReadRow", own: 1, inherited: 1},
		{name: "authored SQL retains scope", row: "SelfReadRow", authored: true, own: 1},
		{name: "authored input with different source alias", row: "SelfReadRow", authored: true, alias: true, own: 1},
		{name: "explicit linked selection", row: "SelfReadRow", authored: true, explicit: true},
		{name: "bare generated shape name", row: "SelfReadRow", authored: true, tag: `typeName:"SelfReadRow"`, own: 1},
		{name: "qualified linked shape name", row: "SelfReadRow", authored: true, tag: `typeName:"generated.SelfReadRow"`},
		{name: "bare DQL view shape name", row: "SelfReadRow", authored: true, viewType: "SelfReadRow", own: 1},
		{name: "qualified DQL view shape name", row: "SelfReadRow", authored: true, viewType: "generated.SelfReadRow"},
		{name: "borrowed selection", row: "SelfReadRow", borrowed: true},
		{name: "same package other component", row: "OtherReadRow"},
		{name: "authored source declaration", row: "AuthoredReadRow"},
		{name: "foreign destination", row: "SelfReadRow", foreign: true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			component := compiled.Component.Clone()
			packaged := compiled.Source.PackageComponent.Clone()
			view := packaged.Views[0].Clone()
			view.Name = "Evidence"
			view.Key.Name = "Evidence"
			view.Namespace = ""
			p := &spec.Parameter{Name: "Evidence", Source: spec.BindSource{Kind: "view", Name: "Evidence"}, TypeExpr: "[]*" + tc.row}
			packaged.Parameters = []*spec.Parameter{p}
			packaged.Views = []*spec.View{view}
			authored := &spec.Component{Name: component.Name}
			if tc.viewType != "" {
				authored.Views = []*spec.View{{Name: "Evidence", TypeName: tc.viewType}}
			}
			if tc.authored {
				declaration := *p
				declaration.TypeExpr = "?"
				declaration.Tag = tc.tag
				if tc.alias {
					declaration.Source.Name = "PriorEvidence"
				}
				if tc.explicit {
					declaration.TypeExpr = p.TypeExpr
				}
				authored.Parameters = []*spec.Parameter{&declaration}
			}
			if tc.borrowed {
				authored.Settings = &spec.Settings{Generation: &spec.GenerationSettings{BorrowedSQLRows: []spec.BorrowedSQLRow{{Package: pkg, Type: tc.row}}}}
			}
			if tc.foreign {
				component.TypeContext.PackagePath = "example.com/foreign"
			}
			sourceCopy := *compiled.Source
			sourceCopy.PackageComponent = packaged
			own, inherited, err := generatedCurrentAuthority(ctx, &sourceCopy, component, authored, compiled.TypeResolver)
			if err != nil || len(own) != tc.own || len(inherited) != tc.inherited {
				t.Fatalf("own=%v inherited=%v err=%v", own, inherited, err)
			}
		})
	}
	t.Run("selected source differs from descriptor", func(t *testing.T) {
		sourceCopy := *compiled.Source
		packaged := sourceCopy.PackageComponent.Clone()
		p := &spec.Parameter{Name: "Evidence", Source: spec.BindSource{Kind: "view", Name: "Evidence"}, TypeExpr: "[]*SelfReadRow"}
		view := packaged.Views[0].Clone()
		view.Name = "Evidence"
		view.Key.Name = "Evidence"
		view.Namespace = ""
		packaged.Parameters = []*spec.Parameter{p}
		packaged.Views = []*spec.View{view}
		sourceCopy.PackageComponent = packaged
		writeSourceFile(t, root, "generated/self_read.go", "// Code generated by Datly for Probe; DO NOT EDIT.\npackage generated\ntype SelfReadRow struct { Id *int; Added string }\n")
		own, inherited, err := generatedCurrentAuthority(ctx, &sourceCopy, compiled.Component, &spec.Component{Name: "Probe"}, compiled.TypeResolver)
		if err != nil || len(own) != 0 || len(inherited) != 0 {
			t.Fatalf("stale declaration admitted: %v %v %v", own, inherited, err)
		}
	})

}
