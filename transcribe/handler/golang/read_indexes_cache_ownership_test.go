package golang

import (
	"bytes"
	"go/format"
	"go/token"
	"os"
	"path/filepath"
	"testing"

	"github.com/viant/datly/spec"
	"github.com/viant/datly/transcribe/generate"
	plan "github.com/viant/datly/transcribe/handler/ast"
)

func TestReadIndexesNativeCacheOwnership(t *testing.T) {
	semantic := rootSemanticPlan(plan.OperationPost, false)
	semantic.ReadCollections = []plan.ReadCollection{{Name: "Previous", InputPath: plan.FieldPath{"Input", "Previous"}, Type: spec.TypeRef{Name: "Row"}, Fields: []plan.FieldRef{{Field: "ID", Type: spec.TypeRef{Name: "int"}}}}}
	config := Config{Package: "events", PackagePath: "github.com/viant/datly/syncfixture", Factory: "NewEventsHandler", InputType: "Input", OutputType: "Output", Records: rootRecordTypes(semantic, "[]*Row", "[]*Row")}
	config.ReadIndexes = &ReadIndexConfig{Package: config.Package, PackagePath: config.PackagePath, InputType: "Input", Owned: true}
	asset, err := ReadIndexes(semantic, config)
	if err != nil {
		t.Fatal(err)
	}
	var rendered bytes.Buffer
	if err = format.Node(&rendered, token.NewFileSet(), asset.File); err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	input := "package events;type Input struct { Previous []*Row; " + asset.CacheField + " *" + asset.TypeName + " };type Row struct {ID int}"
	if err = os.WriteFile(filepath.Join(dir, "input.go"), []byte(input), 0600); err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile(filepath.Join(dir, "lookup.go"), append([]byte("// Code generated by Datly for Events; DO NOT EDIT.\n\n"), rendered.Bytes()...), 0600); err != nil {
		t.Fatal(err)
	}
	for range 3 {
		if !generate.RetainsReadIndexCache(dir, "lookup.go", "input.go", "Events", "Input", asset.CacheField, asset.TypeName, asset.File) {
			t.Fatal("native cached asset ownership lost")
		}
	}
	(entitySyncFixture{entity: &EntityAsset{File: asset.File}, source: `package events
 import("context";"testing";h "github.com/viant/xdatly/handler")
 type Row struct {ID int};type Input struct {Previous []*Row; ` + asset.CacheField + ` *` + asset.TypeName + `}
 type fields struct{};func(fields)Has(string)bool{return true}
 type projection struct{};func(projection)RootHolder()string{return ""};func(projection)DirectOutput()bool{return true};func(projection)Fields(int,...h.ReadStep)(h.FieldSet,error){return fields{},nil}
 type metadata struct{};func(metadata)Projection(string)(h.ReadProjection,error){return projection{},nil}
 func TestCache(t *testing.T){
 input:=&Input{Previous:[]*Row{{ID:1}}};ctx:=h.WithReadMetadata(context.Background(),metadata{})
 first,err:=input.ReadIndexes(ctx);if err!=nil{t.Fatal(err)}
 second,err:=input.ReadIndexes(context.Background());if err!=nil||second!=first{t.Fatal("cache not retained",err)}
 if err=input.PrepareReadIndexes(ctx);err!=nil{t.Fatal(err)};third,err:=input.ReadIndexes(ctx);if err!=nil||third==first{t.Fatal("cache not rebuilt",err)}
 if err=input.PrepareReadIndexes(context.Background());err==nil{t.Fatal("missing metadata accepted")}
 if _,err=input.ReadIndexes(context.Background());err==nil{t.Fatal("failed prepare retained stale cache")}
 }
 `}).run(t)
}
