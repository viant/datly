package transcribe

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
	"github.com/viant/bindly/resource"
	"github.com/viant/datly/internal/testharness"
	"github.com/viant/datly/internal/testharness/sqlite"
	"github.com/viant/datly/transcribe/column"
	"github.com/viant/datly/typecatalog"
)

// This is a causal regeneration protocol: the later schema evolution and
// borrower checks must observe the same owner files and authoring database.
func TestFactoryBorrowsNativeWriterGraph(t *testing.T) {
	const module = "example.com/nativefactory"
	root, err := filepath.EvalSymlinks(t.TempDir())
	require.NoError(t, err)
	(testharness.GeneratedModule{Path: module}).Write(t, root)
	db := sqlite.New(t)
	require.NoError(t, db.ExecStatements(t.Context(), "CREATE TABLE records(id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT)", "CREATE TABLE children(id INTEGER PRIMARY KEY AUTOINCREMENT,record_id INTEGER REFERENCES records(id),name TEXT)"))
	ownerText := `#package('` + module + `/owner')
#setting($_ = $route('/records','PATCH'))
#setting($_ = $dest('records.go'))
#setting($_ = $connector('main'))
#setting($_ = $input_type('Input'))
#setting($_ = $output_type('Output'))
#define($_ = $Rows<[]*Record>(body/data).Optional())
SELECT r.*,children.*,type(r,'Record'),lifecycle_type(r,'RecordLifecycle'),type(children,'Child','Children')
FROM (${embed:sql/records.sql}) r LEFT JOIN children ON r.id = children.record_id`
	owner := &Source{Name: "Owner", Scope: module + "/dql/owner", Path: filepath.Join(root, "dql/owner/Owner.dql"), Text: ownerText, Connector: "main", Types: typecatalog.NewCatalog(), ColumnRefiner: column.New(column.Connections{"main": db.DB})}
	writeSourceFile(t, root, "dql/owner/Owner.dql", ownerText)
	writeSourceFile(t, root, "dql/owner/sql/records.sql", "SELECT * FROM records")
	owner.Resources, err = resource.New().WithDefault(os.DirFS(filepath.Join(root, "dql/owner")))
	require.NoError(t, err)
	writeSourceFile(t, root, "owner/lifecycle.go", `package owner
import("context";"github.com/viant/xdatly/handler")
type RecordLifecycle struct{}
func (*RecordLifecycle) Init(context.Context,*Record,handler.LifecycleContext[Record,handler.NoParent,Output]) error{return nil}
func (*RecordLifecycle) Validate(context.Context,*Record,handler.LifecycleContext[Record,handler.NoParent,Output]) error{return nil}
func (*RecordLifecycle) AfterSequence(context.Context,*Record,handler.LifecycleContext[Record,handler.NoParent,Output]) error{return nil}
func (*RecordLifecycle) AfterQueue(context.Context,*Record,handler.LifecycleContext[Record,handler.NoParent,Output]) error{return nil}
`)
	_, err = (Generator{Operation: "patch"}).Generate(t.Context(), GenerationRequest{Source: owner, Destination: root})
	require.NoError(t, err)
	writeSourceFile(t, root, "graph/handler.go", `package graph
import("context";"github.com/viant/xdatly/handler")
type Handler struct{}
func NewGraph() handler.Contract[Input,Output] {return &Handler{}}
func (*Handler) Exec(context.Context,handler.Session,*Input,*Output) error {return nil}
`)
	writeSourceFile(t, root, "graph/input.go", `// Code generated by Datly for Graph; DO NOT EDIT.
package graph
type Input struct { Body *Body; cache any }
`)
	writeSourceFile(t, root, "graph/body.go", `// Code generated by Datly for Graph; DO NOT EDIT.
package graph
import "`+module+`/owner"
type Body struct { Rows []*owner.Record; cache any }
`)

	graphText := `#package('` + module + `/graph')
#import('own','` + module + `/owner')
#setting($_ = $handler_factory('NewGraph','Graph'))
#setting($_ = $route('/graph','PATCH'))
#setting($_ = $connector('main'))
#setting($_ = $input_type('Input'))
#setting($_ = $output_type('Output'))
#setting($_ = $source_input('Input'))
#setting($_ = $source_member('Input','cache'))
#setting($_ = $source_member('Body','cache'))
#define($_ = $Body<*Body>(body/).Optional())
#setting($_ = $borrow_sql_row('Body/Rows','` + module + `/owner','Record','dql/owner/Owner.dql','Owner','Rows'))
SELECT type(b,'Body'),dest(b,'body.go'),r.*,type(r,'own.Record','Rows') FROM Body b CROSS JOIN records r`
	graph := &Source{Name: "Graph", Scope: module + "/dql", Path: filepath.Join(root, "dql/Graph.dql"), Text: graphText, Connector: "main", Types: typecatalog.NewCatalog(), ColumnRefiner: owner.ColumnRefiner}
	writeSourceFile(t, root, "dql/Graph.dql", graphText)
	var stable map[string]string
	for round := 0; round < 3; round++ {
		if round == 2 {
			_, err = (Generator{Operation: "patch"}).Generate(t.Context(), GenerationRequest{Source: owner, Destination: root})
			require.NoError(t, err)
		}
		before := sourceHandlerSnapshot(t, filepath.Join(root, "owner"))
		freshGraph := &Source{Name: graph.Name, Scope: graph.Scope, Path: graph.Path, Text: graph.Text, Connector: graph.Connector, Types: typecatalog.NewCatalog(), ColumnRefiner: graph.ColumnRefiner}
		compiled, err := (&Discovery{BaseDir: root, ColumnRefiner: graph.ColumnRefiner}).CompileSource(t.Context(), freshGraph)
		require.NoError(t, err)
		_, err = (Generator{Operation: "post"}).Generate(t.Context(), GenerationRequest{Compiled: compiled, Destination: root})
		require.NoError(t, err)
		require.Nil(t, compiled.Component.RootView, "graph cannot acquire writer execution")
		require.Equal(t, before, sourceHandlerSnapshot(t, filepath.Join(root, "owner")), "reference-only borrowing changed owner artifacts")
		text, err := os.ReadFile(filepath.Join(root, "owner/records.go"))
		require.NoError(t, err)
		require.Contains(t, string(text), "Children")
		if round == 2 {
			require.Contains(t, string(text), "Note")
		}
		router, err := os.ReadFile(filepath.Join(root, "graph/router.go"))
		require.NoError(t, err)
		require.False(t, strings.Contains(string(router), `mutation:`))
		current := sourceHandlerSnapshot(t, filepath.Join(root, "graph"))
		if round == 0 {
			stable = current
		}
		if round == 1 {
			require.Equal(t, stable, current, "unchanged borrowing must regenerate identically")
			require.NoError(t, db.ExecStatements(t.Context(), "ALTER TABLE records ADD COLUMN note TEXT"))
			require.NotNil(t, compiled.ExternalHandler.ValidateOwnerSources)
			require.ErrorContains(t, compiled.ExternalHandler.ValidateOwnerSources(nil), "native schema changed after source compilation")
		}

	}
}
