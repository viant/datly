func TestOrdinaryAuthoredLocalIndependentViewOverlayAuthorityFailsClosed(t *testing.T) {
	for _, mode := range []string{"context_env", "persistent_private_goenv"} {
		t.Run(mode, func(t *testing.T) {
			root := ordinaryReadFixture(t, false, false)
			overlayDir := filepath.Join(root, "overlay with space")
			if err := os.Mkdir(overlayDir, 0700); err != nil {
				t.Fatal(err)
			}
			replacement := filepath.Join(overlayDir, "replacement.go")
			if err := os.WriteFile(replacement, []byte("// Code generated by Previous; DO NOT EDIT.\npackage rows\ntype ReadRow struct { Replaced string }\n"), 0600); err != nil {
				t.Fatal(err)
			}
			overlay := filepath.Join(overlayDir, "overlay.json")
			data, err := json.Marshal(map[string]any{"Replace": map[string]string{filepath.Join(root, "rows/readrow.go"): replacement}})
			if err != nil {
				t.Fatal(err)
			}
			if err = os.WriteFile(overlay, data, 0600); err != nil {
				t.Fatal(err)
			}
			flags := "\"-overlay=" + overlay + "\""
			build := &gobuild.Context{Dir: root}
			if mode == "context_env" {
				build.Env = []string{"GOFLAGS=" + flags}
			} else {
				t.Setenv("GOFLAGS", "")
				goenv := filepath.Join(root, "private-goenv")
				if err = os.WriteFile(goenv, []byte("GOFLAGS="+flags+"\n"), 0600); err != nil {
					t.Fatal(err)
				}
				build.Env = []string{"GOENV=" + goenv}
			}
			command := exec.Command("go", "env", "GOFLAGS")
			command.Dir = build.Dir
			command.Env = append(os.Environ(), build.Env...)
			actual, err := command.CombinedOutput()
			if err != nil || strings.TrimSpace(string(actual)) != flags {
				t.Fatalf("effective Go flag authority not established: %q %v", actual, err)
			}
			requireOrdinaryReadUnlinkedOrRejected(t, root, build)
		})
	}
}

func TestOrdinaryAuthoredLocalIndependentViewPackageOriginIsNotAuthorship(t *testing.T) {
	root := ordinaryReadFixture(t, false, false)
	file := filepath.Join(root, "rows/readrow.go")
	raw, err := os.ReadFile(file)
	if err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile(file, append([]byte("// Code generated by another tool; DO NOT EDIT.\n\n"), raw...), 0600); err != nil {
		t.Fatal(err)
	}
	result, plan, err := ordinaryReadPlan(root)
	if err != nil {
		t.Fatal(err)
	}
	origin, err := result.TypeResolver.ResolveWithProvenance(ordinaryReadPackage + ".ReadRow")
	if err != nil || origin.Origin != typecatalog.TypeOriginPackage {
		t.Fatalf("control must reach package-origin source: %v", err)
	}
	row := plan.ViewByType("ReadRow")
	if row == nil || row.Ownership != gen.ViewGenerated {
		t.Fatal("generated declaration borrowed solely from package origin")
	}
}
