func requireOrdinaryReadUnlinkedOrRejected(t *testing.T, root string, build *gobuild.Context) {
	t.Helper()
	result, plan, err := ordinaryReadPlanWithBuild(root, build)
	if err != nil {
		t.Logf("existing fail-closed rejection: %v", err)
		return
	}
	for _, row := range plan.Views {
		if row.Ownership == gen.ViewLinked && strings.HasSuffix(row.DescriptorKey, ".ReadRow") {
			t.Fatalf("nonadmitted declaration acquired linked ownership: %s", row.DescriptorKey)
		}
	}
	for _, ref := range result.Views {
		if ref != nil && strings.HasSuffix(ref.DescriptorKey, ".ReadRow") {
			t.Fatal("unadmitted descriptor acquired a linked reference")
		}
	}
}

func TestOrdinaryAuthoredLocalIndependentViewRejectsNonConcreteDeclarations(t *testing.T) {
	for _, replacement := range []struct{ name, text string }{
		{"body_alias", "package rows\ntype BodyRow struct { ID int }\ntype ReadRow = BodyRow\n"},
		{"scalar_alias", "package rows\ntype ReadRow = int\n"},
		{"defined_scalar", "package rows\ntype ReadRow int\n"},
		{"defined_slice", "package rows\ntype ReadChild struct { ID int }\ntype ReadRow []*ReadChild\n"},
	} {
		t.Run(replacement.name, func(t *testing.T) {
			root := ordinaryReadFixture(t, false, false)
			if err := os.WriteFile(filepath.Join(root, "rows/readrow.go"), []byte(replacement.text), 0600); err != nil {
				t.Fatal(err)
			}
			requireOrdinaryReadUnlinkedOrRejected(t, root, &gobuild.Context{Dir: root})
		})
	}
}

