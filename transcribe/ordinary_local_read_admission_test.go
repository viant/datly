const ordinaryReadPackage = "example.com/ordinaryread/rows"

func ordinaryReadFixture(t *testing.T, generated, mismatch bool) string {
	t.Helper()
	root := t.TempDir()
	for _, name := range []string{"go.mod", "rows/readrow.go", "dql/probe.dql"} {
		sourceName := name
		if name == "go.mod" {
			sourceName += ".txt"
		}
		data, err := os.ReadFile(filepath.Join("testdata/ordinary_local_read_ownership", sourceName))
		if err != nil {
			t.Fatal(err)
		}
		if name == "rows/readrow.go" && generated {
			data = append([]byte("// Code generated by Datly for Previous; DO NOT EDIT.\n\n"), data...)
		}
		if name == "dql/probe.dql" && mismatch {
			data = []byte(strings.Replace(string(data), ".Cardinality('Many')", ".Cardinality('Many').TypeName('rows.OtherRead')", 1))
		}
		path := filepath.Join(root, name)
		if err = os.MkdirAll(filepath.Dir(path), 0700); err != nil {
			t.Fatal(err)
		}
		if err = os.WriteFile(path, data, 0600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}
func ordinaryReadPlan(root string) (*transcribe.Result, *gen.Plan, error) {
	return ordinaryReadPlanWithBuild(root, &gobuild.Context{Dir: root})
}
func ordinaryReadPlanWithBuild(root string, build *gobuild.Context) (*transcribe.Result, *gen.Plan, error) {
	project, err := (&transcribe.Discovery{BaseDir: root, Include: []string{"example.com/ordinaryread/dql"}, SourceFile: "probe.dql", GoBuild: build}).Compile(context.Background())
	if err != nil {
		return nil, nil, err
	}
	result := project.Components[0]
	plan, err := gen.New(gen.Input{Component: result.Component, Declarations: result.Declarations, Views: result.Views, ViewBindings: result.ViewBindings, TypeResolver: result.TypeResolver, TargetPackage: result.Component.TypeContext.PackagePath, Resources: result.Source.Resources}).Plan()
	return result, plan, err
}
func TestOrdinaryAuthoredLocalIndependentViewRetainsNativeReadOwner(t *testing.T) {
	result, plan, err := ordinaryReadPlan(ordinaryReadFixture(t, false, false))
	if err != nil {
		t.Fatal(err)
	}
	row := plan.ViewByType("ReadRow")
	if row == nil {
		t.Fatal("missing canonical independent read plan")
	}
	if row.Ownership != gen.ViewLinked || row.DescriptorKey != ordinaryReadPackage+".ReadRow" {
		t.Fatalf("authored independent read must remain linked, got ownership=%s descriptor=%q; catalog alone does not establish row selection", row.Ownership, row.DescriptorKey)
	}
	if len(row.Fields) != 0 || row.Destination != "" {
		t.Fatal("linked read must not emit duplicate fields or destination")
	}
	origin, err := result.TypeResolver.ResolveWithProvenance(ordinaryReadPackage + ".ReadRow")
	if err != nil || origin.Origin != typecatalog.TypeOriginPackage {
		t.Fatalf("genuine authored source authority missing: %v", err)
	}
	body := plan.ViewByType("BodyRow")
	if body == nil || body.Ownership != gen.ViewGenerated {
		t.Fatal("SQL-derived body owner changed")
	}
}
