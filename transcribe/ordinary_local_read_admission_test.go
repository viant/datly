func TestOrdinaryAuthoredLocalIndependentViewSourceHasAndRelationMetadata(t *testing.T) {
	result, _, err := ordinaryReadPlan(ordinaryReadFixture(t, false, false))
	if err != nil {
		t.Fatal(err)
	}
	descriptor, err := result.TypeResolver.Descriptor(ordinaryReadPackage + ".ReadRow")
	if err != nil {
		t.Fatal(err)
	}
	shape := xshape.New(descriptor, result.TypeResolver.Descriptor)
	fields, err := shape.Fields()
	if err != nil {
		t.Fatal(err)
	}
	foundRelation := false
	for _, field := range fields {
		if field.Name == "Children" && strings.Contains(string(field.Tag), "read_children") {
			foundRelation = true
		}
	}
	if !foundRelation {
		t.Fatal("source relation metadata lost")
	}
	has, err := shape.FieldsAt("Has")
	if err != nil || len(has) != 2 || has[0].Name != "ID" || has[1].Name != "Children" {
		t.Fatalf("source Has contract changed: %v", err)
	}
	childHas, err := shape.FieldsAt("Children.Has")
	if err != nil || len(childHas) != 2 || childHas[1].Name != "ParentID" {
		t.Fatalf("source child Has contract changed: %v", err)
	}
}
